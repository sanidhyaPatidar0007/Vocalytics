"""Server-controlled, organization-isolated file storage.

Layout (every name below is generated by the server; a user-supplied file name
is only stored as display metadata in the database):

    <STORAGE_ROOT>/orgs/<org_id>/originals/<dataset_id>/<uuid>.<ext>
    <STORAGE_ROOT>/orgs/<org_id>/versions/<dataset_id>/v<NNNN>-<uuid8>.parquet
    <STORAGE_ROOT>/orgs/<org_id>/tmp/<random>/...   scratch space, always removed
    <STORAGE_ROOT>/tmp/<random>/...                  scratch space without an org

The database stores paths relative to STORAGE_ROOT. ``resolve_relative``
refuses anything that would escape the storage root (path traversal).
"""

from __future__ import annotations

import contextlib
import hashlib
import os
import re
import shutil
import stat
import tempfile
import time
import unicodedata
import uuid
from collections.abc import Iterator
from pathlib import Path

from config.settings import get_settings
from core.constants import SUPPORTED_UPLOAD_EXTENSIONS
from core.errors import PermissionDeniedError, ValidationError

_COPY_CHUNK = 1024 * 1024
_WINDOWS_INVALID = re.compile(r'[<>:"/\\|?*\x00-\x1f\x7f]')


def storage_root() -> Path:
    root = get_settings().storage_root
    root.mkdir(parents=True, exist_ok=True)
    return root.resolve()


def _positive_int(value: object, label: str) -> int:
    if not isinstance(value, int) or isinstance(value, bool) or value <= 0:
        raise ValidationError(f"Invalid {label}.")
    return value


def org_dir(org_id: int) -> Path:
    path = storage_root() / "orgs" / str(_positive_int(org_id, "organization"))
    path.mkdir(parents=True, exist_ok=True)
    return path


def resolve_relative(relative: str) -> Path:
    """Resolve a stored relative path, refusing absolute paths and traversal."""
    if not relative or not isinstance(relative, str):
        raise PermissionDeniedError("Invalid storage path.")
    if os.path.isabs(relative) or relative.startswith(("/", "\\")) or ":" in relative:
        raise PermissionDeniedError("Invalid storage path.")
    root = storage_root()
    candidate = (root / relative).resolve()
    if candidate == root or root not in candidate.parents:
        raise PermissionDeniedError("Invalid storage path.")
    return candidate


def to_relative(path: Path) -> str:
    """Convert an absolute path inside the storage root into its stored form."""
    resolved = path.resolve()
    root = storage_root()
    if root not in resolved.parents:
        raise PermissionDeniedError("Invalid storage path.")
    return resolved.relative_to(root).as_posix()


def new_original_path(org_id: int, dataset_id: int, extension: str) -> Path:
    ext = extension.lower()
    if ext not in SUPPORTED_UPLOAD_EXTENSIONS:
        raise ValidationError("Unsupported file type.")
    folder = org_dir(org_id) / "originals" / str(_positive_int(dataset_id, "dataset"))
    folder.mkdir(parents=True, exist_ok=True)
    return folder / f"{uuid.uuid4().hex}{ext}"


def new_version_path(org_id: int, dataset_id: int, version_number: int) -> Path:
    folder = org_dir(org_id) / "versions" / str(_positive_int(dataset_id, "dataset"))
    folder.mkdir(parents=True, exist_ok=True)
    number = _positive_int(version_number, "version")
    return folder / f"v{number:04d}-{uuid.uuid4().hex[:8]}.parquet"


@contextlib.contextmanager
def temporary_directory(org_id: int | None = None, prefix: str = "op-") -> Iterator[Path]:
    """A scratch directory that is removed on success, failure and cancellation."""
    base = (org_dir(org_id) / "tmp") if org_id else (storage_root() / "tmp")
    base.mkdir(parents=True, exist_ok=True)
    path = Path(tempfile.mkdtemp(prefix=prefix, dir=base))
    try:
        yield path
    finally:
        remove_tree_quietly(path)


def _fsync(path: Path) -> None:
    with open(path, "rb+") as handle:
        os.fsync(handle.fileno())


@contextlib.contextmanager
def atomic_output(dest: Path) -> Iterator[Path]:
    """Yield a temporary path next to ``dest`` and publish it atomically.

    The caller writes the complete file to the yielded path. On success the
    file is flushed to disk and moved into place with ``os.replace`` (atomic on
    the same volume). On any exception the partial file is deleted, so a
    reader never observes a half-written file.
    """
    dest.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(prefix=f".{dest.name}.", suffix=".partial", dir=dest.parent)
    os.close(fd)
    tmp = Path(tmp_name)
    try:
        yield tmp
        _fsync(tmp)
        os.replace(tmp, dest)
    except BaseException:
        remove_file_quietly(tmp)
        raise


def atomic_write_bytes(dest: Path, data: bytes) -> None:
    with atomic_output(dest) as tmp:
        tmp.write_bytes(data)


def atomic_copy(src: Path, dest: Path) -> None:
    with atomic_output(dest) as tmp:
        with open(src, "rb") as reader, open(tmp, "wb") as writer:
            shutil.copyfileobj(reader, writer, _COPY_CHUNK)


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(_COPY_CHUNK), b""):
            digest.update(chunk)
    return digest.hexdigest()


def make_read_only(path: Path) -> None:
    os.chmod(path, stat.S_IREAD | stat.S_IRGRP | stat.S_IROTH)


def remove_file_quietly(path: Path, attempts: int = 5) -> bool:
    """Delete a file, tolerating Windows' transient locks. Returns success."""
    for attempt in range(attempts):
        try:
            if not path.exists():
                return True
            if not os.access(path, os.W_OK):
                os.chmod(path, stat.S_IWRITE | stat.S_IREAD)
            path.unlink()
            return True
        except PermissionError:
            time.sleep(0.05 * (attempt + 1))
        except FileNotFoundError:
            return True
        except OSError:
            return False
    return False


def remove_tree_quietly(path: Path) -> None:
    if not path.exists():
        return
    for dirpath, dirnames, filenames in os.walk(path, topdown=False):
        for name in filenames:
            remove_file_quietly(Path(dirpath) / name)
        for name in dirnames:
            with contextlib.suppress(OSError):
                (Path(dirpath) / name).rmdir()
    with contextlib.suppress(OSError):
        path.rmdir()


def directory_size_bytes(path: Path) -> int:
    total = 0
    if not path.exists():
        return 0
    for dirpath, _dirnames, filenames in os.walk(path):
        for name in filenames:
            with contextlib.suppress(OSError):
                total += (Path(dirpath) / name).stat().st_size
    return total


def sanitize_display_filename(name: str, max_length: int = 200) -> str:
    """Make a user-supplied file name safe to display and to keep as metadata.

    Only the last path component is kept, control and reserved characters are
    removed. The result is never used to build a storage path.
    """
    raw = (name or "").replace("\\", "/").split("/")[-1]
    cleaned = unicodedata.normalize("NFKC", raw)
    cleaned = re.sub(r"\s+", " ", cleaned)  # tabs/newlines become spaces before control chars are dropped
    cleaned = _WINDOWS_INVALID.sub("", cleaned)
    cleaned = re.sub(r" +", " ", cleaned).strip(" .")
    if not cleaned:
        cleaned = "upload"
    if len(cleaned) > max_length:
        stem, dot, ext = cleaned.rpartition(".")
        if dot and 0 < len(ext) <= 10:
            cleaned = f"{stem[: max_length - len(ext) - 1]}.{ext}"
        else:
            cleaned = cleaned[:max_length]
    return cleaned


def file_extension(name: str) -> str:
    sanitized = sanitize_display_filename(name)
    _, dot, ext = sanitized.rpartition(".")
    return f".{ext.lower()}" if dot else ""
